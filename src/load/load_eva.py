def cargar_hechos(cur, df, geografias, cultivos, tiempos):
    hechos = df[
        [
            "codigo_municipio",
            "codigo_cultivo",
            "periodo",
            "area_sembrada",
            "area_cosechada",
            "produccion",
            "rendimiento",
        ]
    ].copy()

    hechos["sk_geografia"] = hechos["codigo_municipio"].map(
        geografias
    )
    hechos["sk_cultivo"] = hechos["codigo_cultivo"].map(cultivos)
    hechos["sk_tiempo"] = hechos["periodo"].map(tiempos)

    if hechos[
        ["sk_geografia", "sk_cultivo", "sk_tiempo"]
    ].isna().any().any():
        raise ValueError(
            "Existen hechos sin correspondencia en alguna dimensión."
        )

    columnas = [
        "sk_geografia",
        "sk_cultivo",
        "sk_tiempo",
        "area_sembrada",
        "area_cosechada",
        "produccion",
        "rendimiento",
    ]

    registros = list(
        hechos[columnas].itertuples(index=False, name=None)
    )

    execute_values(
        cur,
        """
        INSERT INTO eva.fact_produccion_agricola (
            sk_geografia,
            sk_cultivo,
            sk_tiempo,
            area_sembrada,
            area_cosechada,
            produccion,
            rendimiento
        )
        VALUES %s
        ON CONFLICT (
            sk_geografia, sk_cultivo, sk_tiempo
        )
        DO UPDATE SET
            area_sembrada = EXCLUDED.area_sembrada,
            area_cosechada = EXCLUDED.area_cosechada,
            produccion = EXCLUDED.produccion,
            rendimiento = EXCLUDED.rendimiento
        """,
        registros,
        page_size=5000,
    )

    logger.info("Hechos procesados: %s", f"{len(registros):,}")


