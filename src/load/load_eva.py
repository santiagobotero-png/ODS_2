# ============================================================

def main():
    df = leer_eva()

    conexion = psycopg2.connect(
        host=os.getenv("ETL_DB_HOST", "localhost"),
        port=os.getenv("ETL_DB_PORT", "5433"),
        dbname=os.getenv("ETL_DB_NAME", os.getenv("POSTGRES_DB")),
        user=os.getenv("ETL_DB_USER", os.getenv("POSTGRES_USER")),
        password=os.getenv(
            "ETL_DB_PASSWORD",
            os.getenv("POSTGRES_DB_PASSWORD"),
        ),
    )

    try:
        with conexion:
            with conexion.cursor() as cur:
                logger.info("Preparando esquema y tablas EVA...")
                cur.execute(DDL)

                logger.info("Cargando dimensión geográfica...")
                geografias = cargar_geografia(cur, df)

                logger.info("Cargando dimensión de cultivos...")
                cultivos = cargar_cultivos(cur, df)

                logger.info("Cargando dimensión temporal...")
                tiempos = cargar_tiempo(cur, df)

                logger.info("Cargando hechos agrícolas...")
                cargar_hechos(
                    cur, df, geografias, cultivos, tiempos
                )

        logger.info("Carga EVA completada correctamente.")

    except Exception:
        logger.exception("Error durante la carga EVA. Se hará rollback.")
        raise

    finally:
        conexion.close()


if __name__ == "__main__":
    main()
