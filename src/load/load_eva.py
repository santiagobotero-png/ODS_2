def leer_eva():
    if not ARCHIVO_EVA.exists():
        raise FileNotFoundError(
            f"No existe el archivo procesado: {ARCHIVO_EVA}"
        )

    # Los códigos se leen como texto para preservar ceros iniciales.
    df = pd.read_csv(
        ARCHIVO_EVA,
        dtype={
            "codigo_departamento": "string",
            "codigo_municipio": "string",
            "codigo_cultivo": "string",
            "periodo": "string",
        },
    )

    df["codigo_departamento"] = (
        df["codigo_departamento"].str.strip().str.zfill(2)
    )
    df["codigo_municipio"] = (
        df["codigo_municipio"].str.strip().str.zfill(5)
    )
    df["codigo_cultivo"] = df["codigo_cultivo"].str.strip()
    df["periodo"] = df["periodo"].str.strip()

    logger.info("Archivo leído: %s", ARCHIVO_EVA.name)
    logger.info("Registros de entrada: %s", f"{len(df):,}")
    return df


