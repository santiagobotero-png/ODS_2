-- ============================================================
-- ODS2 - WEATHER
-- PostgreSQL 16
-- ============================================================

CREATE SCHEMA IF NOT EXISTS weather;

-- ============================================================
-- DIMENSIÓN GEOGRAFÍA
-- Grain: un municipio
-- ============================================================

CREATE TABLE IF NOT EXISTS weather.dim_geografia (
    sk_geografia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo_departamento VARCHAR(2),
    departamento VARCHAR(100),

    codigo_municipio VARCHAR(5) NOT NULL UNIQUE,
    municipio VARCHAR(255) NOT NULL,

    latitud NUMERIC(9, 6),
    longitud NUMERIC(9, 6),

    CONSTRAINT ck_weather_latitud
        CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),

    CONSTRAINT ck_weather_longitud
        CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);

-- ============================================================
-- DIMENSIÓN FECHA
-- Grain: un día calendario
-- ============================================================

CREATE TABLE IF NOT EXISTS weather.dim_fecha (
    sk_fecha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fecha DATE NOT NULL UNIQUE,
    anio SMALLINT NOT NULL,
    mes SMALLINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nombre_mes VARCHAR(20) NOT NULL,
    trimestre SMALLINT NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    dia SMALLINT NOT NULL CHECK (dia BETWEEN 1 AND 31),
    dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    nombre_dia VARCHAR(20) NOT NULL,
    es_fin_de_semana BOOLEAN NOT NULL
);

-- ============================================================
-- HECHOS CLIMÁTICOS DIARIOS
-- Grain: un municipio por fecha
-- ============================================================

CREATE TABLE IF NOT EXISTS weather.fact_clima_diario (
    sk_clima_diario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sk_geografia INTEGER NOT NULL
        REFERENCES weather.dim_geografia(sk_geografia),

    sk_fecha INTEGER NOT NULL
        REFERENCES weather.dim_fecha(sk_fecha),

    temperatura_media NUMERIC(10, 2),
    temperatura_maxima NUMERIC(10, 2),
    temperatura_minima NUMERIC(10, 2),
    precipitacion NUMERIC(10, 2),
    humedad_relativa_media NUMERIC(10, 2),
    evapotranspiracion_et0 NUMERIC(10, 2),

    source_batch_id VARCHAR(255) NOT NULL,

    CONSTRAINT uq_weather_clima_geografia_fecha
        UNIQUE (sk_geografia, sk_fecha),

    CONSTRAINT ck_weather_temperaturas
        CHECK (
            temperatura_minima IS NULL
            OR temperatura_maxima IS NULL
            OR temperatura_minima <= temperatura_maxima
        ),

    CONSTRAINT ck_weather_humedad
        CHECK (
            humedad_relativa_media IS NULL
            OR humedad_relativa_media BETWEEN 0 AND 100
        ),

    CONSTRAINT ck_weather_precipitacion
        CHECK (precipitacion IS NULL OR precipitacion >= 0),

    CONSTRAINT ck_weather_et0
        CHECK (evapotranspiracion_et0 IS NULL
               OR evapotranspiracion_et0 >= 0)
);

-- Índices útiles para consultas por fecha y municipio.
CREATE INDEX IF NOT EXISTS ix_weather_clima_fecha
    ON weather.fact_clima_diario (sk_fecha);

CREATE INDEX IF NOT EXISTS ix_weather_clima_geografia
    ON weather.fact_clima_diario (sk_geografia);